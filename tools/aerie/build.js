#!/usr/bin/env node
// Generates the Aerie's build as a datapack function (dev-server/world/datapacks/avian-aerie): a rock crag
// rising from the ground, a nest of twisted logs on top around a blackstone-and-gold capture pad, a beacon in
// the middle whose beam marks it from anywhere, and a stair spiralling up the outside. Every coordinate is
// relative (~), so it builds wherever it's run:
//   /execute positioned <x> <ground+1> <z> run function avian:aerie/build
// The capture zone in aerie.conf must match: the pad is the top of the crag, TOP blocks above that position.
// Deterministic (seeded), so regenerating gives the same build. Run: node tools/aerie/build.js
const fs = require('fs'), path = require('path');

const TOP = 21;          // the pad's floor, blocks above the given position
const PAD = 6;           // capture pad radius
const NEST_IN = 7, NEST_OUT = 10;

let seed = 0xA371E;
const rnd = () => { seed = (seed + 0x6D2B79F5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const pick = (list) => list[Math.floor(rnd() * list.length)];

const out = [];
const set = (x, y, z, b) => out.push(`setblock ~${x} ~${y} ~${z} ${b}`);
const fill = (x1, y1, z1, x2, y2, z2, b, mode = '') =>
  out.push(`fill ~${x1} ~${y1} ~${z1} ~${x2} ~${y2} ~${z2} ${b}${mode ? ' ' + mode : ''}`);

// The crag's radius at each height: a thick base, a waist, then flaring out to carry the nest.
function radius(y) {
  if (y <= 3) return 8 - y * 0.5;           // 8 → 6.5
  if (y <= 12) return 6;                    // the waist
  return Math.min(NEST_OUT, 6 + (y - 12) * 0.5);   // flares to 10 under the nest
}
const rock = ['tuff', 'tuff', 'cobbled_deepslate', 'deepslate', 'andesite', 'stone', 'polished_tuff', 'tuff_bricks'];

out.push('# The Aerie (avian-factions #21), generated by tools/aerie/build.js: do not edit by hand.');
// Clear the space first (only above the ground the position stands on).
fill(-13, 0, -13, 13, TOP + 9, 13, 'air');

// The crag, layer by layer, with a ragged edge.
for (let y = 0; y <= TOP; y++) {
  const r = radius(y);
  for (let x = -NEST_OUT; x <= NEST_OUT; x++) {
    for (let z = -NEST_OUT; z <= NEST_OUT; z++) {
      const d = Math.hypot(x, z);
      if (d > r + (rnd() - 0.5) * 1.2) continue;
      let b = pick(rock);
      if (y < 2 && rnd() < 0.25) b = pick(['mossy_cobblestone', 'moss_block']);
      set(x, y, z, b);
    }
  }
}

// The pad: blackstone with gold rings, gilded flecks, the beacon in the middle on iron.
for (let x = -PAD; x <= PAD; x++) {
  for (let z = -PAD; z <= PAD; z++) {
    const d = Math.hypot(x, z);
    if (d > PAD + 0.4) continue;
    let b = 'polished_blackstone_bricks';
    if (Math.abs(d - 3.2) < 0.5 || Math.abs(d - 5.6) < 0.45) b = 'gold_block';
    else if (rnd() < 0.12) b = 'gilded_blackstone';
    else if (rnd() < 0.15) b = 'cracked_polished_blackstone_bricks';
    set(x, TOP, z, b);
  }
}
fill(-1, TOP - 1, -1, 1, TOP - 1, 1, 'iron_block');
set(0, TOP, 0, 'beacon');
set(0, TOP + 1, 0, 'air');

// The nest: a ring of twisted logs, two to three high, ragged, with twigs and straw.
const logs = ['dark_oak_log', 'dark_oak_log', 'spruce_log', 'stripped_dark_oak_log', 'mangrove_roots', 'dark_oak_wood'];
for (let x = -NEST_OUT; x <= NEST_OUT; x++) {
  for (let z = -NEST_OUT; z <= NEST_OUT; z++) {
    const d = Math.hypot(x, z);
    if (d < NEST_IN - 0.3 || d > NEST_OUT + 0.3) continue;
    set(x, TOP, z, pick(['dark_oak_planks', 'packed_mud', 'rooted_dirt']));   // the nest's floor under the rim
    // The way in: a gap where the stair arrives (south side).
    if (z >= NEST_IN - 1 && Math.abs(x) <= 1) continue;
    const h = d > NEST_OUT - 1 ? 1 + Math.floor(rnd() * 2) : 2 + Math.floor(rnd() * 2);
    for (let y = 1; y <= h; y++) {
      const axis = Math.abs(x) > Math.abs(z) ? 'z' : 'x';
      const log = pick(logs);
      set(x, TOP + y, z, log.endsWith('roots') ? log : `${log}[axis=${axis}]`);
    }
    if (rnd() < 0.18) set(x, TOP + h + 1, z, pick(['dark_oak_fence', 'spruce_fence', 'hay_block', 'dead_bush']));
  }
}
// Feathers: white and black wool tufts on the rim, and lanterns on posts at the four corners.
for (let i = 0; i < 10; i++) {
  const a = rnd() * Math.PI * 2, d = NEST_IN + 1 + rnd() * 2;
  const x = Math.round(Math.cos(a) * d), z = Math.round(Math.sin(a) * d);
  if (z >= NEST_IN - 1 && Math.abs(x) <= 1) continue;
  set(x, TOP + 4, z, pick(['white_wool', 'black_wool', 'light_gray_wool']));
}
for (const [x, z] of [[7, 0], [-7, 0], [0, -7], [5, 5], [-5, 5]]) {
  fill(x, TOP + 1, z, x, TOP + 3, z, 'dark_oak_fence');
  set(x, TOP + 4, z, 'soul_lantern');
}

// The stair: a ledge spiralling up the outside from the south, two wide, arriving at the nest's gap.
// One block up every two steps; air kept clear above it.
const steps = TOP * 2;
const turn = Math.PI * 1.5;            // three-quarters of a turn on the way up
for (let i = 0; i <= steps; i++) {
  const y = Math.floor(i / 2);
  const a = Math.PI / 2 - turn + (turn * i) / steps;   // ends at +z (south)
  const r = radius(y) + 1.6;
  for (const w of [0, 1]) {
    const x = Math.round(Math.cos(a) * (r + w)), z = Math.round(Math.sin(a) * (r + w));
    set(x, y, z, pick(['deepslate_bricks', 'deepslate_bricks', 'cracked_deepslate_bricks', 'polished_deepslate']));
    fill(x, y + 1, z, x, y + 3, z, 'air');
  }
}
// The last steps into the gap.
fill(-1, TOP, NEST_IN - 1, 1, TOP, NEST_OUT + 2, 'deepslate_bricks');
fill(-1, TOP + 1, NEST_IN - 1, 1, TOP + 3, NEST_OUT + 2, 'air');

const dir = path.join(__dirname, '../../dev-server/world/datapacks/avian-aerie/data/avian/function/aerie');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'build.mcfunction'), out.join('\n') + '\n');
fs.writeFileSync(path.join(dir, 'clear.mcfunction'),
  '# Removes the Aerie built at this position (tools/aerie/build.js); the ground below stays.\n'
  + `fill ~-13 ~ ~-13 ~13 ~${TOP + 9} ~13 air\n`);
console.log(`build.mcfunction: ${out.length} commands; pad floor at +${TOP}, capture zone: x/z -${PAD}..${PAD}, y +${TOP + 1}..+${TOP + 7}`);
